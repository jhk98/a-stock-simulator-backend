package com.myproject.stocksimulator.signup.dto;

import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;

/**
 * 회원가입 요청 DTO
 *
 * <p> 사용자가 회원가입 화면에서 입력한 정보를 전달받는다. </p>
 *
 * 주요 검증 조건
 * 1. 로그인 아이디는 영문과 숫자 4~20자
 * 2. 비밀번호는 영문, 숫자, 특수문자를 포함한 8~20자
 * 3. 이름은 1~10자
 * 4. 전화번호는 010-0000-0000 형식
 * 5. 이메일은 올바른 이메일 형식
 *
 * <p> 이메일 인증 완료 여부와 아이디·이메일 중복 여부는 SignupService에서 별도로 검증한다. </p>
 */
public record SignupRequest(

        // ============================================================
        // 1. 로그인 아이디
        // ============================================================

        @NotBlank(message = "아이디를 입력해주세요.")
        @Pattern(regexp = "^[a-zA-Z0-9]{4,20}$", message = "아이디는 영문과 숫자 4~20자로 입력해주세요.")
        String loginId,


        // ============================================================
        // 2. 비밀번호
        // ============================================================

        @NotBlank(message = "비밀번호를 입력해주세요.")
        @Pattern(regexp = "^(?=.*[A-Za-z])(?=.*\\d)(?=.*[^A-Za-z0-9\\s])\\S{8,20}$", message = "비밀번호는 영문, 숫자, 특수문자를 포함한 8~20자로 입력해주세요.")
        String password,


        // ============================================================
        // 3. 이름
        // ============================================================

        @NotBlank(message = "이름을 입력해주세요.")
        @Size(max = 10, message = "이름은 10자 이내로 입력해주세요.")
        String name,


        // ============================================================
        // 4. 전화번호 (하이픈 없이 숫자 11자리 입력)
        // ============================================================

        @NotBlank(message = "전화번호를 입력해주세요.")
        @Pattern(regexp = "^010[0-9]{8}$", message = "전화번호는 하이픈 없이 010으로 시작하는 숫자 11자리로 입력해주세요.")
        String phoneNumber,


        // ============================================================
        // 5. 이메일
        // ============================================================

        @NotBlank(message = "이메일을 입력해주세요.")
        @Email(message = "올바른 이메일 형식이 아닙니다.")
        @Size(max = 255, message = "이메일은 255자 이내로 입력해주세요.")
        String email
) {
}